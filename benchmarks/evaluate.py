"""Print precision, recall and coverage per entity type on the synthetic corpus.

    python benchmarks/evaluate.py [--per-kind 200] [--strict]

The corpus is generated by tests/synth.py. It checks that detectors and
validators agree with the formats they claim to support; it says nothing
about recall on real-world text, which is messier. Measure on your own data.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "tests"))

import synth
from depii import Redactor


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--per-kind", type=int, default=200)
    parser.add_argument("--seed", type=int, default=7)
    parser.add_argument("--strict", action="store_true")
    args = parser.parse_args()

    samples = synth.corpus(args.seed, args.per_kind)
    scores = synth.evaluate(Redactor(strict=args.strict).scan, samples)

    print(f"{len(samples)} samples, {len(synth.NEGATIVES)} of them negatives\n")
    print("| Entity | Planted | Recall | Coverage | Precision |")
    print("|---|---:|---:|---:|---:|")
    for entity in sorted(scores):
        s = scores[entity]
        recall = f"{s.recall:.3f}" if s.planted else "-"
        coverage = f"{s.coverage:.3f}" if s.planted else "-"
        print(f"| {entity} | {s.planted} | {recall} | {coverage} | {s.precision:.3f} |")


if __name__ == "__main__":
    main()
